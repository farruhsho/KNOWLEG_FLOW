/// A handbook section. [generated] sections (ORT structure and scoring) are
/// built at runtime from `assets/data/exam_blueprints.json` so the facts can
/// never drift from the verified blueprint again (CMS-08).
class HandbookSection {
  final String id;
  final Map<String, String> title;
  final Map<String, String> body; // Markdown
  final HandbookGenerated? generated;

  const HandbookSection({
    required this.id,
    required this.title,
    this.body = const {},
    this.generated,
  });
}

enum HandbookGenerated { ortStructure, ortScoring }

