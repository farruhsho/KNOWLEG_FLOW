/// Codes the student types in (ARCHITECTURE §9): a friend's referral code,
/// a promo code and a group join code.
///
/// Validation here is only a typo guard so an obviously malformed code never
/// costs a server round trip (promo attempts are rate-limited). The server
/// stays the source of truth for whether a code exists, is active or was
/// already used.
abstract final class SocialCodes {
  /// `users/{uid}.referral_code`: 6 characters from this alphabet (no
  /// 0/O/1/I, so a code read aloud cannot be mistyped).
  static const referralAlphabet = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  static const referralLength = 6;

  /// `promo_codes/{CODE}`: 4–20 characters `A-Z0-9`.
  static const promoMinLength = 4;
  static const promoMaxLength = 20;

  /// Group join codes are generated by `groupCreate`; their exact format is
  /// the server's business, so the client accepts any plausible code.
  static const groupMinLength = 4;
  static const groupMaxLength = 12;

  /// Longest code any field accepts (input limit for text fields).
  static const maxInputLength = promoMaxLength;

  static final _separators = RegExp(r'[\s\-_.]');
  static final _promo = RegExp(r'^[A-Z0-9]{4,20}$');
  static final _group = RegExp(r'^[A-Z0-9]{4,12}$');

  /// Cyrillic letters that look like Latin ones. Students in Kyrgyzstan often
  /// type on a Russian/Kyrgyz layout, so «АВС123» must read as `ABC123`.
  static const _homoglyphs = {
    'А': 'A',
    'В': 'B',
    'Е': 'E',
    'К': 'K',
    'М': 'M',
    'Н': 'H',
    'О': 'O',
    'Р': 'P',
    'С': 'C',
    'Т': 'T',
    'У': 'Y',
    'Х': 'X',
  };

  /// Upper-cases [raw], drops spaces/dashes and maps Cyrillic look-alikes to
  /// Latin letters.
  static String normalize(String raw) {
    final upper = raw.toUpperCase().replaceAll(_separators, '');
    final out = StringBuffer();
    for (final ch in upper.split('')) {
      out.write(_homoglyphs[ch] ?? ch);
    }
    return out.toString();
  }

  static bool isReferralCode(String code) =>
      code.length == referralLength &&
      code.split('').every(referralAlphabet.contains);

  static bool isPromoCode(String code) => _promo.hasMatch(code);

  static bool isGroupCode(String code) => _group.hasMatch(code);
}
